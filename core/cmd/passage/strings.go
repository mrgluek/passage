// table is the strings for lang, English where a translation is missing.
func table(lang string) map[string]string {
	out := map[string]string{}
	for k, v := range texts["en"] {
		out[k] = v
	}
	for k, v := range texts[lang] {
		out[k] = v
	}
	return out
}

// language picks a table from a locale name such as ru-RU.
func language(locale string) string {
	if strings.HasPrefix(strings.ToLower(locale), "ru") {
		return "ru"
	}
	return "en"
}

type tr map[string]string

func (t tr) f(key string, args ...any) string {
	s, ok := t[key]
	if !ok {
		s = key
	}
	if len(args) == 0 {
		return s
	}
	return fmt.Sprintf(s, args...)
}

func (t tr) quantity(key string, count int64, args ...any) string {
	form := "other"
	if _, russian := t[key+"_few"]; russian {
		switch {
		case count%10 == 1 && count%100 != 11:
			form = "one"
		case count%10 >= 2 && count%10 <= 4 && (count%100 < 12 || count%100 > 14):
			form = "few"
		default:
			form = "many"
		}
	} else if count == 1 {
		form = "one"
	}
	return t.f(key+"_"+form, args...)
}
